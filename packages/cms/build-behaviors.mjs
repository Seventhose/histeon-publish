import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Doc 23 item 120: the behaviours of Histeon's pages (tabs, toggles, reveal on scroll, videos and maps on a click), the
 * same script and style Histeon for WordPress serves (plugin/assets/front/behaviors.*, in the vendored snapshot),
 * embedded for the static build: the packaged app serves them without reading files.
 */
const packageRoot = path.dirname(fileURLToPath(import.meta.url));
const front = path.join(packageRoot, "vendor/histos/plugin/assets/front");
const [script, style] = await Promise.all([readFile(path.join(front, "behaviors.js"), "utf8"), readFile(path.join(front, "behaviors.css"), "utf8")]);
const output = [
  "// Generated by packages/cms/build-behaviors.mjs from the vendored Histeon plugin/assets/front/behaviors.*. Do not edit.",
  `export const BEHAVIORS_SCRIPT = ${JSON.stringify(script)};`,
  `export const BEHAVIORS_CSS = ${JSON.stringify(style)};`,
  "",
].join("\n");
const target = path.join(packageRoot, "src/behaviors.generated.ts");
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8").catch(() => "")) !== output) {
    process.stderr.write("packages/cms/src/behaviors.generated.ts non corrisponde allo snapshot di Histeon: esegui node packages/cms/build-behaviors.mjs.\n");
    process.exit(1);
  }
} else {
  await writeFile(target, output, "utf8");
  process.stdout.write("Comportamenti di Histeon incorporati.\n");
}
