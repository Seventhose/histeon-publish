import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Embeds the AI manual for Histeon prototypes and the kits to copy (doc 17 item 3), so the packaged app, the CLI and
 * the connector serve them without files. The connector client gets its own copies because it is bundled alone, with
 * no dependency on this package. The manual's kit (§1.3) is assets/kit-minimo.html: the build writes the file into the
 * manual, and the check refuses a manual whose kit is not the file.
 */
const packageRoot = path.dirname(fileURLToPath(import.meta.url));
const assets = path.join(packageRoot, "assets");
const kits = {
  minimo: await readFile(path.join(assets, "kit-minimo.html"), "utf8"),
  sito: await readFile(path.join(assets, "kit-sito.html"), "utf8"),
};
const manualFile = path.join(assets, "prototipo-ai.md");
const written = await readFile(manualFile, "utf8");
const KIT_FENCE = /(### 1\.3 [^\n]*\n[\s\S]*?```html\n)([\s\S]*?)(```)/u;
if (!KIT_FENCE.test(written)) {
  process.stderr.write("assets/prototipo-ai.md: manca il blocco ```html del kit nel §1.3.\n");
  process.exit(1);
}
const manual = written.replace(KIT_FENCE, (_match, before, _kit, after) => `${before}${kits.minimo}${after}`);
const check = process.argv.includes("--check");
const outputs = new Map([
  [path.join(packageRoot, "src/prototype-manual.generated.ts"), ["// Generated by packages/cms/build-prototype-manual.mjs from packages/cms/assets/prototipo-ai.md. Do not edit.", `export const PROTOTYPE_AI_MANUAL = ${JSON.stringify(manual)};`, ""].join("\n")],
  [path.join(packageRoot, "../connector/src/manual.generated.ts"), ["// Generated by packages/cms/build-prototype-manual.mjs from packages/cms/assets/prototipo-ai.md. Do not edit.", `export const PROTOTYPE_AI_MANUAL = ${JSON.stringify(manual)};`, ""].join("\n")],
]);
const kitsSource = ["// Generated by packages/cms/build-prototype-manual.mjs from packages/cms/assets/kit-*.html. Do not edit.", `export const PROTOTYPE_KITS: Readonly<Record<${Object.keys(kits).map((kind) => JSON.stringify(kind)).join(" | ")}, string>> = ${JSON.stringify(kits, null, 2)};`, ""].join("\n");
outputs.set(path.join(packageRoot, "src/prototype-kits.generated.ts"), kitsSource);
outputs.set(path.join(packageRoot, "../connector/src/kits.generated.ts"), kitsSource);
if (check) {
  if (manual !== written) {
    process.stderr.write("Il kit del §1.3 di assets/prototipo-ai.md non è assets/kit-minimo.html: esegui node packages/cms/build-prototype-manual.mjs.\n");
    process.exit(1);
  }
  for (const [target, output] of outputs) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== output) {
      process.stderr.write(`${path.relative(path.join(packageRoot, "../.."), target)} non corrisponde ad assets/: esegui node packages/cms/build-prototype-manual.mjs.\n`);
      process.exit(1);
    }
  }
} else {
  if (manual !== written) await writeFile(manualFile, manual, "utf8");
  for (const [target, output] of outputs) await writeFile(target, output, "utf8");
  process.stdout.write("Manuale e kit del prototipo incorporati.\n");
}
