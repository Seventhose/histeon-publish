import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = path.dirname(fileURLToPath(import.meta.url));
const [tokens, utilities, recipes, acssMap, articleComponents] = await Promise.all([
  readFile(path.join(packageRoot, "assets/histos-css/xb-tokens.css"), "utf8"),
  readFile(path.join(packageRoot, "assets/histos-css/histos.css"), "utf8"),
  readFile(path.join(packageRoot, "assets/histos-css/recipes.json"), "utf8"),
  readFile(path.join(packageRoot, "assets/histos-css/acss-map.json"), "utf8"),
  readFile(path.join(packageRoot, "assets/histos-css/article-components.json"), "utf8"),
]);
const { tokens: acssTokens, classes: acssClasses } = JSON.parse(acssMap);
const output = [
  "// Generated by build-histos-css-assets.mjs from GPL-3.0-or-later Histeon CSS assets. Do not edit.",
  `export const HISTOS_TOKENS_CSS = ${JSON.stringify(tokens)};`,
  `export const HISTOS_UTILITIES_CSS = ${JSON.stringify(utilities)};`,
  `export const HISTOS_RECIPES = ${JSON.stringify(JSON.parse(recipes))} as const;`,
  `export const HISTOS_ARTICLE_COMPONENTS = ${JSON.stringify(JSON.parse(articleComponents))} as const;`,
  "/** Automatic.css names with a Histeon CSS equivalent, as the builder's AcssImport has them (assets/histos-css/acss-map.json). */",
  `export const HISTOS_ACSS_MAP: { readonly tokens: Readonly<Record<string, string>>; readonly classes: Readonly<Record<string, string>> } = ${JSON.stringify({ tokens: acssTokens, classes: acssClasses })};`,
  "",
].join("\n");
await writeFile(path.join(packageRoot, "src/histos-css-assets.generated.ts"), output, "utf8");
process.stdout.write("Histeon CSS assets embedded for the local CMS runtime.\n");
