import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

/**
 * Bundles the connector client into one dependency-free file for Node 18 or later. The app copies it into
 * <data>/connector/ when the connector is turned on, so its version is always the app's.
 */
const packageRoot = path.dirname(fileURLToPath(import.meta.url));
const { version } = JSON.parse(await readFile(path.join(packageRoot, "../../package.json"), "utf8"));
await build({
  entryPoints: [path.join(packageRoot, "src/bin.ts")],
  outfile: path.join(packageRoot, "dist/histos-publish-connector.mjs"),
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node18",
  legalComments: "none",
  banner: { js: "#!/usr/bin/env node\n// Histeon Publish connector (GPL-3.0-or-later). Generated by packages/connector/build.mjs: do not edit." },
  define: { __HP_VERSION__: JSON.stringify(version) },
  logLevel: "warning",
});
